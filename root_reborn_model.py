def _to_float(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        for attr in ("tao", "rao"):
            v = getattr(x, attr, None)
            if v is not None:
                return float(v) / (1e9 if attr == "rao" else 1.0)
    return None


def resolve_dereg_floor(cfg: dict | None = None) -> tuple[float, str]:
    """Live dereg floor: the EMA of whichever non-immune subnet is currently first
    in the prune queue. Returns (floor, provenance) — provenance is printed so a
    stale fallback can never be mistaken for a live read."""
    from dereg_watch import load_dereg_state

    if cfg and cfg.get("dereg_floor_tao"):
        return float(cfg["dereg_floor_tao"]), "explicit override"
    d = load_dereg_state()
    if d.get("floor_tao"):
        return float(d["floor_tao"]), (
            f"LIVE — netuid {d.get('floor_netuid')} is the prune target, "
            f"read {str(d.get('checked_at'))[:10]}"
        )
    return DEREG_FLOOR_FALLBACK, "STALE FALLBACK — run dereg_watch.py"


def fetch_live(netuid: int = NETUID_SN21, floor: float | None = None) -> dict:
    """One finney connection -> SN21 pool state + §6 market context + root-stake
    concentration. Raises on failure so --live never silently uses stale values."""
    # Ported to raw storage (2026-07-22): bittensor 9.x's all_subnets() can't
    # decode the spec-430 runtime and bittensor 11 has no bulk pool read.
    from chain_compat import qmap, substrate

    if floor is None:
        floor, _ = resolve_dereg_floor()

    with substrate() as sub:
        block = int(sub.get_block_number(sub.get_chain_head()))
        tao_map = qmap(sub, "SubnetTAO", 1e9)
        alpha_map = qmap(sub, "SubnetAlphaIn", 1e9)

    rows = []
    for nu in sorted(set(tao_map) | set(alpha_map)):
        if nu == 0:  # root has no alpha pool
            continue
        tao_in = tao_map.get(nu)
        alpha_in = alpha_map.get(nu)
        price = (tao_in / alpha_in) if (tao_in and alpha_in and alpha_in > 0) else None
        if not price or price <= 0:
            continue
        rows.append({"netuid": nu, "tao_in": tao_in, "alpha_in": alpha_in, "price": price})

    sn21 = next((r for r in rows if r["netuid"] == netuid), None)
    if sn21 is None:
        raise RuntimeError(f"netuid {netuid} pool not found / invalid in all_subnets()")

    n = len(rows)
    by_tao = sorted(rows, key=lambda r: r["tao_in"])
    by_price = sorted(rows, key=lambda r: r["price"])

    def rank(lst):
        idx = next(i for i, r in enumerate(lst) if r["netuid"] == netuid)
        return idx + 1, round(100 * (idx + 1) / len(lst), 1)

    taos = [r["tao_in"] for r in rows]
    prices = [r["price"] for r in rows]
    tao_rank, tao_pct = rank(by_tao)
    price_rank, price_pct = rank(by_price)
    tao_median = statistics.median(taos)
    top_decile = sorted(taos)[int(0.9 * n)]

    # Root-stake concentration (netuid 0) -> R-E / Q2
    root = None
    try:
        from chain_compat import fetch_metagraph

        mg0 = fetch_metagraph(0)
        stakes = sorted((float(s) for s in mg0.S), reverse=True)
        tot = sum(stakes) or 1.0
        root = {
            "n": len(stakes),
            "total": tot,
            **{f"top{k}": round(100 * sum(stakes[:k]) / tot, 1) for k in (1, 3, 4, 5, 10)},
        }
    except Exception as e:  # noqa: BLE001
        root = {"error": str(e)}

    return {
        "block": block,
        "pool": {
            "alpha_reserve": sn21["alpha_in"],
            "tao_reserve": sn21["tao_in"],
            "alpha_price_tao": sn21["price"],
        },
        "market": {
            "n_priced": n,
            "tao_in": sn21["tao_in"],
            "tao_rank": tao_rank, "tao_pct": tao_pct,
            "tao_median": tao_median, "tao_ratio_median": sn21["tao_in"] / tao_median,
            "tao_top_decile": top_decile, "in_top_decile": sn21["tao_in"] >= top_decile,
            "price": sn21["price"],
            "price_rank": price_rank, "price_pct": price_pct,
            "price_median": statistics.median(prices),
            "floor": floor,
            "spot_above_floor_pct": (sn21["price"] / floor - 1) * 100,
            "n_below_floor": sum(1 for p in prices if p < floor),
            "root": root,
        },
    }


# Back-compat thin wrapper (pool only).
def fetch_live_pool(netuid: int = NETUID_SN21) -> dict:
    live = fetch_live(netuid)
    return {"block": live["block"], **live["pool"]}


