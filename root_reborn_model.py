def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    cfg = dict(INPUTS)
    source = DEFAULTS_SOURCE + " (baked-in defaults)"
    market = None
    if "--live" in argv:
        print("Pulling live SN21 pool + market state from finney …")
        live = fetch_live(NETUID_SN21, resolve_dereg_floor(cfg)[0])
        cfg["alpha_reserve"] = live["pool"]["alpha_reserve"]
        cfg["alpha_price_tao"] = live["pool"]["alpha_price_tao"]
        market = live["market"]
        blk = f"block {live['block']:,}" if live.get("block") else "block ?"
        source = f"live finney all_subnets() @ {blk}"
        print(f"  live alpha_reserve = {cfg['alpha_reserve']:,.0f}")
        print(f"  live tao_reserve   = {live['pool']['tao_reserve']:,.0f}")
        print(f"  live spot price    = {cfg['alpha_price_tao']:.6f} TAO/alpha")

    run(cfg, source=source)

    if "--write-doc" in argv:
        if "--live" not in argv:
            print("\n[--write-doc with baked-in defaults — pass --live for fresh chain values]")
        print("\nUpdating assessment doc …")
        write_doc(cfg, source, market)


