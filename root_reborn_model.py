def write_doc(cfg, source: str, market: dict | None, doc_path: Path = DOC_PATH) -> None:
    text = doc_path.read_text(encoding="utf-8")
    if DOC_MARK_BEGIN not in text or DOC_MARK_END not in text:
        raise RuntimeError(
            f"markers not found in {doc_path}; add a block delimited by\n"
            f"  {DOC_MARK_BEGIN}\n  {DOC_MARK_END}")
    pre = text.split(DOC_MARK_BEGIN, 1)[0]
    post = text.split(DOC_MARK_END, 1)[1]
    block = render_live_block(cfg, source, market)
    doc_path.write_text(pre + block + post, encoding="utf-8")
    print(f"  wrote live-figures block -> {doc_path}")


